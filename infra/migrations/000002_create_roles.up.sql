DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'fidibeki_app') THEN
        CREATE ROLE fidibeki_app;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'fidibeki_admin') THEN
        CREATE ROLE fidibeki_admin;
    END IF;
END;
$$;

ALTER ROLE fidibeki_app NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
ALTER ROLE fidibeki_admin NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION BYPASSRLS;

REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO fidibeki_app, fidibeki_admin;
REVOKE EXECUTE ON FUNCTION set_updated_at() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION set_updated_at() TO fidibeki_app, fidibeki_admin;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO fidibeki_admin;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT USAGE, SELECT ON SEQUENCES TO fidibeki_admin;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT EXECUTE ON FUNCTIONS TO fidibeki_admin;
